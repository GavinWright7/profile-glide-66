/**
 * Reads scripts/bls-occupations-raw.txt and writes src/data/occupations.ts
 * Run: node scripts/build-bls-occupations.mjs
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, '..');
const rawPath = path.join(__dirname, 'bls-occupations-raw.txt');
const outPath = path.join(root, 'src', 'data', 'occupations.ts');

const SEE_RE = /, see:\s*(.+)$/i;

function normKey(s) {
  return s.trim().toLowerCase().replace(/\s+/g, ' ');
}

const raw = fs.readFileSync(rawPath, 'utf8');
const lines = raw.split(/\r?\n/);
const map = new Map();

function add(name) {
  if (!name) return;
  if (/^https?:\/\//i.test(name)) return;
  const key = normKey(name);
  if (!key) return;
  if (!map.has(key)) map.set(key, name);
}

for (const line of lines) {
  const t = line.trim();
  if (!t) continue;
  if (t === '0-9') continue;
  if (/^[A-Z]$/.test(t)) continue;

  const m = t.match(SEE_RE);
  if (m) {
    const alias = t.slice(0, m.index).trim();
    const canonical = m[1].trim();
    add(alias);
    add(canonical);
  } else {
    add(t);
  }
}

const sorted = [...map.values()].sort((a, b) => a.localeCompare(b, 'en', { sensitivity: 'base' }));

const body = sorted.map((s) => JSON.stringify(s)).join(',\n  ');

const ts = `/**
 * BLS Occupational Outlook Handbook–style titles: alternate titles (before ", see:"),
 * standalone lines, and each canonical "see:" target. Deduped (case-insensitive), sorted A–Z.
 * Generated by scripts/build-bls-occupations.mjs — do not edit by hand.
 */
export const BLS_OCCUPATIONS: readonly string[] = [
  ${body},
] as const;
`;

fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(outPath, ts, 'utf8');
console.error(`Wrote ${outPath} (${sorted.length} occupations)`);
